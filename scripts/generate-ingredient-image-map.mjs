import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const projectDirectory = resolve(scriptDirectory, "..");
const imageDirectory = join(projectDirectory, "assets/images/ingredients");
const outputPath = join(projectDirectory, "src/assets/ingredientImageSources.ts");
const outputDirectory = dirname(outputPath);
const sourcePrefix = relative(outputDirectory, imageDirectory).replaceAll("\\", "/");
const filenames = readdirSync(imageDirectory)
  .filter((filename) => filename.endsWith(".png"))
  .sort((left, right) => left.localeCompare(right));

const entries = filenames.map((filename) => {
  const slug = filename.slice(0, -4);
  return `  ${JSON.stringify(slug)}: require(${JSON.stringify(`${sourcePrefix}/${filename}`)}),`;
});

writeFileSync(
  outputPath,
  [
    "// Generated by scripts/generate-ingredient-image-map.mjs.",
    "// Run the script again after changing assets/images/ingredients.",
    'import type { ImageSourcePropType } from "react-native";',
    "",
    "export const ingredientImageSources: Record<string, ImageSourcePropType> = {",
    ...entries,
    "};",
    "",
  ].join("\n")
);

console.log(`Generated ${filenames.length} ingredient image entries.`);
